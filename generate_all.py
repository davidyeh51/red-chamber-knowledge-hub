# Parse raw markdown files and integrate
all_lessons_data = []

files = [f for f in sorted(os.listdir(SRC_DIR)) if f.endswith('.md') and not f.startswith('00_')]

for f in files:
    filepath = os.path.join(SRC_DIR, f)
    with open(filepath, 'r', encoding='utf-8') as fp:
        raw = fp.read()
    
    meta = FILE_METAS.get(f, {})
    if not meta:
        print(f"Warning: No curated meta for {f}")
        continue
        
    # parse frontmatter
    fm = {}
    body_text = raw
    if raw.startswith('---'):
        parts = raw.split('---', 2)
        if len(parts) >= 3:
            fm_text = parts[1]
            body_text = parts[2]
            for line in fm_text.splitlines():
                if ':' in line:
                    k, v = line.split(':', 1)
                    fm[k.strip()] = v.strip().strip('"').strip("'")
                    
    title = fm.get('title', f.replace('.md', ''))
    
    # parse sections
    note_part = ""
    full_part = ""
    if "## 筆記內容（得到筆記摘要）" in body_text:
        sections = body_text.split("## 筆記內容（得到筆記摘要）")
        after = sections[1]
        if "## 來源全文" in after:
            n_sub, f_sub = after.split("## 來源全文", 1)
            note_part = n_sub.strip()
            full_part = f_sub.strip()
        else:
            note_part = after.strip()
    elif "## 來源全文" in body_text:
        before, after = body_text.split("## 來源全文", 1)
        note_part = before.strip()
        full_part = after.strip()
    else:
        note_part = body_text.strip()
        
    sec_blocks = re.split(r'\n###\s*', '\n' + note_part)
    sections = []
    for sb in sec_blocks:
        sb = sb.strip()
        if not sb:
            continue
        lines = sb.splitlines()
        header = lines[0].strip().strip('*').strip()
        content = "\n".join(lines[1:]).strip()
        sections.append({
            'question': header,
            'content': content
        })
        
    lesson_obj = {
        "id": f"lesson_{meta['order']:02d}",
        "order": meta["order"],
        "filename": f,
        "title": title,
        "short_title": meta["short_title"],
        "module_id": meta["module"],
        "action_title": meta["action_title"],
        "core_problem": meta["core_problem"],
        "key_insights": meta["key_insights"],
        "humanities_cultivation": meta["humanities_cultivation"],
        "modern_application": meta["modern_application"],
        "golden_quote": meta["golden_quote"],
        "speaker_notes": meta["speaker_notes"],
        "characters": meta["characters"],
        "keywords": meta["keywords"],
        "source_note": note_part,
        "source_full": full_part,
        "sections": sections,
        "source_url": fm.get("source_url", ""),
        "source_note_url": fm.get("source_note_url", "")
    }
    all_lessons_data.append(lesson_obj)

